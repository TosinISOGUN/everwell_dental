// Builds responsive AVIF + WebP copies of every photograph in assets-source/photos/ into
// public/images/ and writes src/data/images.generated.ts (intrinsic sizes the components use).
// Run with: bun run images. Originals are never modified.
import fs from "node:fs";
import path from "node:path";
import sharp from "sharp";

const root = path.resolve(import.meta.dirname, "..");
const SRC = path.join(root, "assets-source/photos");
const OUT = path.join(root, "public/images");
const widths = [480, 768, 1080, 1600, 2000];

/**
 * id -> original file, with an optional crop ({ left, top, width, height } in source pixels) for
 * portraits taken from wider frames. All photographs are stock images (see README).
 */
const photos = {
  heroMain: { file: "hero-main.jpg" },
  heroXray: { file: "hero-xray.jpg" },
  consultation: { file: "consultation.jpg" },
  serviceGeneral: { file: "service-general.jpg" },
  serviceCosmetic: { file: "service-cosmetic.jpg" },
  serviceRestorative: { file: "service-restorative.jpg" },
  serviceEmergency: { file: "service-emergency.jpg" },
  smileBand: { file: "smile-band.jpg" },
  clinicWide: { file: "clinic-wide.jpg" },
  clinicChair: { file: "clinic-chair.jpg" },
  teamMarcus: { file: "team-marcus.jpg", crop: { left: 250, top: 0, width: 1280, height: 1600 } },
  teamGrace: { file: "team-grace.jpg", crop: { left: 0, top: 150, width: 2400, height: 3000 } },
  teamRohan: { file: "team-rohan.jpg", crop: { left: 1450, top: 720, width: 950, height: 1187 } },
};

const open = (id) => {
  const { file, crop } = photos[id];
  const img = sharp(path.join(SRC, file));
  return crop ? img.extract(crop) : img;
};

fs.rmSync(OUT, { recursive: true, force: true });
fs.mkdirSync(OUT, { recursive: true });
const manifest = {};

for (const id of Object.keys(photos)) {
  const source = await open(id).toBuffer();
  const meta = await sharp(source).metadata();
  const w = meta.width;
  const h = meta.height;
  const sizes = [...new Set([...widths.filter((x) => x < w), Math.min(w, widths.at(-1))])].sort(
    (a, b) => a - b,
  );
  for (const size of sizes) {
    const base = path.join(OUT, `${id}-${size}`);
    const img = sharp(source).resize({ width: size, withoutEnlargement: true });
    await img.clone().avif({ quality: 50, effort: 4 }).toFile(`${base}.avif`);
    await img.clone().webp({ quality: 76 }).toFile(`${base}.webp`);
  }
  manifest[id] = { w, h, sizes };
}

const body = `// Generated by scripts/build-images.mjs. Do not edit by hand.\nexport type ImageMeta = { w: number; h: number; sizes: number[] };\n\nexport const images = ${JSON.stringify(manifest, null, 2)} as const satisfies Record<string, ImageMeta>;\n\nexport type ImageId = keyof typeof images;\n`;
fs.writeFileSync(path.join(root, "src/data/images.generated.ts"), body);

// Open Graph images (1200x630), one per page, cropped from the same photographs.
// A [left, top, width, height] rectangle crops a portrait frame to the 1.9:1 card first.
const og = {
  home: ["heroMain", [0, 560, 2400, 1260]],
  services: ["clinicWide"],
  "general-dentistry": ["serviceGeneral", [0, 700, 2400, 1260]],
  "cosmetic-dentistry": ["smileBand", [0, 520, 2400, 1260]],
  "restorative-dentistry": ["serviceRestorative"],
  "emergency-dentistry": ["serviceEmergency"],
  about: ["consultation"],
  "new-patients": ["heroXray"],
  contact: ["clinicWide"],
  privacy: ["clinicChair", [0, 1100, 2400, 1260]],
};
fs.mkdirSync(path.join(root, "public/og"), { recursive: true });
for (const [name, [id, rect]] of Object.entries(og)) {
  let img = open(id);
  if (rect) img = img.extract({ left: rect[0], top: rect[1], width: rect[2], height: rect[3] });
  await img
    .resize(1200, 630, { fit: "cover", position: "centre" })
    .jpeg({ quality: 82, mozjpeg: true })
    .toFile(path.join(root, "public/og", `${name}.jpg`));
}
console.log(`built ${Object.keys(manifest).length} images and ${Object.keys(og).length} og images`);
